"""The decoding behaviour of the pre-rewrite ``TextReader``, as data.

An oracle rather than an implementation, deliberately.  The rewrite that produced
``pyjab/common/textreader.py`` was verified against the implementation it replaced
by keeping that implementation here and comparing the two -- but keeping it meant
keeping the code, and the code was derived from NVDA's GPLv2 ``getTextFromRawBytes``.
Shipping it inside an MIT distribution is the problem the rewrite existed to solve.

So the comparison is the same and the code is gone.  ``DATA`` holds one row per
call with an **explicit** encoding -- ``buffer_hex|chars_len|encoding|expected_hex``
-- where ``expected_hex`` is the decoded text as UTF-8 with surrogates passed
through.  Plain UTF-8 cannot hold the lone surrogates a JAB buffer can produce, and
hex round-trips them exactly.  The rows were generated from
``git show v1.5.0:pyjab/common/textreader.py``.

**Why the calls without an encoding are not in the table.**  When the caller does
not say which encoding it is, ``TextReader`` asks the *machine* --
``locale.getpreferredencoding()`` -- and the answer is UTF-8 on macOS and cp1252 on
Windows.  A row recording the decoded text would therefore record the locale of the
machine that generated it, and the first version of this file did exactly that: it
passed here and failed on Windows, on every row whose expected value contained a
byte that the two encodings disagree about.

What is the same everywhere is *which* encoding gets chosen, so that is what
``SNIFFED_WIDE`` records -- ``buffer_hex|chars_len|1`` when the buffer is read as
UTF-16.  The test checks the choice and then compares against the same
implementation given that encoding explicitly.

Facts about what some code did are not that code.
"""

